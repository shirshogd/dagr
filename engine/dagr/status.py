"""status: live table of a graph map.

render(graph, state) is the runner's after-tick callback; it always rewrites
`.dagr/maps/<slug>/STATUS.md` and returns the plain-text table. Stdlib only.
"""
from __future__ import annotations

import time
from pathlib import Path

from . import graphcore, holds

HEADER = "GENERATED by dagr status - do not edit"
COLS = ["id", "title", "status", "attempts", "min", "cost", "score"]


def _epoch(iso):
    try:
        return time.mktime(time.strptime(iso or "", "%Y-%m-%dT%H:%M:%S"))
    except ValueError:
        return None


def _minutes(rec, status, now):
    t0 = _epoch(rec.get("started"))
    if t0 is None:
        return ""
    if status == "running":
        end = now
    else:
        end = _epoch(rec.get("finished"))
        if end is None:
            return ""
    return f"{max(0.0, end - t0) / 60:.1f}"


def _rows(graph, state, now=None):
    now = now or time.time()
    recs = (state or {}).get("tickets") or {}
    rows = []
    for t in sorted(graph.values(), key=lambda x: x.id):
        if not t.in_scope:
            continue
        rec = recs.get(t.id) or {}
        st = graphcore.effective_status(t, state)
        score = rec.get("reviewer_score")
        rows.append([t.id, (t.title or "")[:40], st, str(int(rec.get("attempts") or 0)),
                     _minutes(rec, st, now), f"${float(rec.get('cost_usd') or 0):.2f}",
                     "" if score is None else str(score)])
    return rows


def _footer(graph, state, rows):
    recs = (state or {}).get("tickets") or {}
    held = graphcore.held_set(graph, state)
    n = len(rows)
    by = {}
    for r in rows:
        by[r[2]] = by.get(r[2], 0) + 1
    spend = sum(float((recs.get(r[0]) or {}).get("cost_usd") or 0) for r in rows)
    st = state or {}
    return (f"running {by.get('running', 0)} | closed {by.get('closed', 0)}/{n} | "
            f"held {len([r for r in rows if r[0] in held or r[2] == 'held'])} | "
            f"failed {by.get('failed', 0)} | spend ${spend:.2f} | "
            f"max concurrency {int(st.get('max_concurrency_reached') or 0)} | "
            f"rate events {len(st.get('rate_limit_events') or [])} | "
            f"rate ceiling {st.get('rate_ceiling') if st.get('rate_ceiling') is not None else '-'}")


def _hold_lines(graph, state):
    """ON HOLD (waiting on you): ticket, question file, the question."""
    rows = holds.held_report(graph, state)
    if not rows:
        return []
    return ["ON HOLD (waiting on you)"] + [f"  {t}  {q}  {txt}" for t, q, txt in rows]


def render_text(graph, state, now=None) -> str:
    rows = _rows(graph, state, now)
    widths = [max(len(COLS[i]), *(len(r[i]) for r in rows)) if rows else len(COLS[i])
              for i in range(len(COLS))]

    def line(cells):
        return "  ".join(c.ljust(w) for c, w in zip(cells, widths)).rstrip()

    out = [line(COLS), line(["-" * w for w in widths])] + [line(r) for r in rows]
    hl = _hold_lines(graph, state)
    return "\n".join(out + ["", _footer(graph, state, rows)] + ([""] + hl if hl else []))


def render_md(graph, state, now=None) -> str:
    rows = _rows(graph, state, now)
    slug = (state or {}).get("map", "")
    out = [f"<!-- {HEADER} -->", f"# STATUS {slug}", "", HEADER, "",
           f"updated {time.strftime('%Y-%m-%dT%H:%M:%S')}", "",
           "| " + " | ".join(COLS) + " |", "|" + "|".join("---" for _ in COLS) + "|"]
    for r in rows:
        out.append("| " + " | ".join(c.replace("|", "/") for c in r) + " |")
    out += ["", _footer(graph, state, rows), ""]
    blk = _hold_lines(graph, state)
    for i, l in enumerate(blk):
        out.append("## " + l if i == 0 else "- " + l.strip())
    if out[-1] != "":
        out.append("")
    return "\n".join(out)


def render(graph, state, map_dir=None, now=None) -> str:
    """Write STATUS.md (always) and return the text table."""
    text = render_text(graph, state, now)
    md = Path(map_dir) if map_dir else (Path(graph.map_dir) if getattr(graph, "map_dir", None)
                                        else None)
    if md is not None and md.is_dir():
        tmp = md / "STATUS.md.tmp"
        tmp.write_text(render_md(graph, state, now), encoding="utf-8", newline="\n")
        tmp.replace(md / "STATUS.md")
    return text


def load(slug, root):
    """-> (map_dir, graph, state). Scope comes from GO.md when it exists, else every ticket
    that has a `model:` key."""
    from . import config, runner
    md = config.map_dir(root, slug)
    if not (md / "tickets").is_dir():
        raise graphcore.GraphError(f"no such map: .dagr/maps/{slug}/tickets")
    ids = [p.stem.split("-", 1)[0] for p in (md / "tickets").glob("T*.md")]
    scope, _err = runner.read_go(md, ids)
    graph = graphcore.load_graph(md, scope=scope, root=Path(root))
    state = graphcore.load_state(md / "state.json", slug)
    return md, graph, state


def run_status(slug, root) -> int:
    try:
        md, graph, state = load(slug, root)
    except (graphcore.GraphError, OSError, ValueError) as e:
        print(f"ERROR: {e}")
        return 2
    print(render(graph, state, md))
    return 0
